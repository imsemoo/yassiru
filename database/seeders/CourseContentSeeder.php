<p>ساعات طويلة، ضغط المسؤول، عدم الأمان الوظيفي. كثير من الأزواج يُفرغون ضغط العمل في بيوتهم.</p>

<h4>3. الأهل والعائلة</h4>
<p>التدخلات، الخلافات مع أم الزوج، الزيارات المرهقة، التوقعات العائلية.</p>

<h4>4. الأولاد</h4>
<p>تربيتهم، دراستهم، سلوكهم، حتى مجيئهم (الحمل والولادة والليالي الطويلة).</p>

<h4>5. المشاكل الصحية</h4>
<p>مرض مزمن، حادث، اكتئاب — تغيّر ديناميكية العلاقة بشكل كبير.</p>

<h3>كيف يؤثر الضغط على العلاقة الزوجية؟</h3>
<ul>
<li><strong>قلة الصبر:</strong> الإنسان المضغوط يثور لأتفه الأسباب.</li>
<li><strong>الانسحاب العاطفي:</strong> يصبح الشريك متاحاً جسدياً لكن غائباً عاطفياً.</li>
<li><strong>قلة الاهتمام:</strong> ينشغل كل طرف بضغوطه الخاصة.</li>
<li><strong>الخلافات التافهة:</strong> يصبح أي شيء صغير سبباً للشجار.</li>
<li><strong>فقدان الحميمية:</strong> سواء العاطفية أو الجسدية.</li>
</ul>

<h3>استراتيجيات التعامل مع الضغط كزوجين</h3>

<h4>1. اعترفا بأنكما تحت ضغط</h4>
<p>الإنكار يزيد الأمور سوءاً. قولا بصراحة: "أنا مضغوط هذه الأيام بسبب العمل، وهذا يؤثر على مزاجي. لا علاقة لك بالأمر، لكني أحتاج صبرك".</p>

<h4>2. لا تواجها الضغط بمفردكما</h4>
<p>الزوجان فريق. عندما يكون أحدكما تحت ضغط، على الآخر أن يقلل أعباءه، لا أن يزيدها.</p>

<h4>3. خصصا وقتاً للاسترخاء معاً</h4>
<p>حتى 30 دقيقة يومياً. مشي معاً، حوار هادئ، كوب شاي، بدون هواتف. هذا الوقت يبني "رصيد عاطفي" تستخدمانه وقت الضغط.</p>

<h4>4. تحدثا، لكن لا تُفرغا ضغوطكما على بعض</h4>
<p>فرق بين: "اليوم كان صعباً، مديري كان سيئاً" (حوار صحي) و"أنا متعب منك ومن البيت وكل شيء" (تفريغ غير صحي).</p>

<h4>5. اتفقا على "إشارة هدنة"</h4>
<p>كلمة أو إشارة تعني: "أنا مرهق الآن، أحتاج نصف ساعة صمت ثم نتحدث". هذا أفضل من الانفجار أو الهروب.</p>

<h4>6. مارسا الشكر معاً</h4>
<p>كل يوم قبل النوم، كل واحد يذكر 3 أشياء يشكر الله عليها. هذه العادة البسيطة تُحوّل انتباهكما من السلبيات إلى الإيجابيات.</p>

<h3>استراتيجيات فردية لإدارة الضغط</h3>

<h4>1. الصلاة</h4>
<p>قال تعالى: <em>"وَاسْتَعِينُوا بِالصَّبْرِ وَالصَّلَاةِ"</em> (البقرة: 45). الصلاة ليست مجرد واجب، بل أعظم أداة لتفريغ الضغط.</p>

<h4>2. الذكر</h4>
<p>قال تعالى: <em>"أَلَا بِذِكْرِ اللَّهِ تَطْمَئِنُّ الْقُلُوبُ"</em> (الرعد: 28). دقائق من الذكر اليومي تخفض مستوى القلق.</p>

<h4>3. الرياضة</h4>
<p>المشي 30 دقيقة يومياً يقلل الضغط بشكل مثبت علمياً.</p>

<h4>4. النوم الكافي</h4>
<p>قلة النوم تُضاعف الضغط. 7-8 ساعات نوم ليست ترفاً، بل ضرورة.</p>

<h4>5. الغذاء الصحي</h4>
<p>ما تأكله يؤثر على مزاجك أكثر مما تظن. قلل السكر والكافيين، أكثر من الماء والخضروات.</p>

<h4>6. الانفصال عن الهاتف</h4>
<p>ساعة واحدة يومياً بدون شاشات. جرّب وستفاجأ بالفرق.</p>

<h3>متى تطلب مساعدة متخصص؟</h3>
<p>اذهبا إلى مستشار أسري أو نفسي إذا:</p>
<ul>
<li>الضغط مستمر لأكثر من 3 أشهر بدون تحسن.</li>
<li>تؤثر الضغوط على صحتك الجسدية.</li>
<li>تفكر في إيذاء نفسك أو غيرك.</li>
<li>الخلافات الزوجية تزداد سوءاً.</li>
<li>لم تعد تشعر بفرح في الأشياء التي كانت تُسعدك.</li>
</ul>

