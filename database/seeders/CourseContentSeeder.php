<h3>حقوق الزوجة على زوجها</h3>

<h4>1. المهر</h4>
<p>حق خالص للزوجة لا يحل للزوج أخذه إلا بطيب نفس منها. قال تعالى: <em>"وَآتُوا النِّسَاءَ صَدُقَاتِهِنَّ نِحْلَةً"</em> (النساء: 4).</p>

<h4>2. النفقة</h4>
<p>الطعام، الشراب، الكسوة، المسكن، العلاج — كل ذلك بالمعروف حسب حال الزوج يسراً وعسراً. قال تعالى: <em>"لِيُنفِقْ ذُو سَعَةٍ مِّن سَعَتِهِ"</em> (الطلاق: 7).</p>

<h4>3. حسن المعاشرة</h4>
<p><em>"وَعَاشِرُوهُنَّ بِالْمَعْرُوفِ"</em> (النساء: 19) — لطف الكلام، طيب المعاملة، ترك الأذى، بذل الحب والاحترام.</p>

<h4>4. العدل</h4>
<p>في حالة التعدد، لا بد من العدل التام في النفقة والمبيت والمعاملة. قال ﷺ: <em>"من كانت له امرأتان فمال إلى إحداهما، جاء يوم القيامة وشقه مائل"</em>.</p>

<h4>5. الصون والحماية</h4>
<p>حمايتها من كل أذى، الغيرة عليها، ستر عيوبها، عدم إفشاء أسرارها.</p>

<h3>حقوق الزوج على زوجته</h3>

<h4>1. الطاعة في المعروف</h4>
<p>طاعته فيما يأمر به مما لا معصية فيه. قال ﷺ: <em>"لا طاعة لمخلوق في معصية الخالق"</em>.</p>

<h4>2. حفظ بيته وماله</h4>
<p>قال ﷺ: <em>"المرأة راعية في بيت زوجها ومسؤولة عن رعيتها"</em>. حفظ البيت والأولاد، وصيانة ماله.</p>

<h4>3. إجابته عند طلبه</h4>
<p>ما لم يكن عذر شرعي — الحيض، المرض، إلخ.</p>

<h4>4. حفظ نفسها في غيبته</h4>
<p>صون عرضها وعرض زوجها، عدم إدخال من يكرهه إلى البيت.</p>

<h4>5. الاحترام وحسن الخلق</h4>
<p>خفض الصوت، طلاقة الوجه، عدم الخروج بدون إذنه — كل هذا من حسن العشرة.</p>

<h3>الحقوق المشتركة</h3>
<ul>
<li><strong>الاستمتاع المشروع:</strong> حق لكلا الطرفين.</li>
<li><strong>التشاور في أمور البيت والأولاد.</strong></li>
<li><strong>التربية الصالحة للأبناء.</strong></li>
<li><strong>التعاون على طاعة الله.</strong></li>
