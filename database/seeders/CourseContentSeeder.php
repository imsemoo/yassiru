<p>"المعروف" كلمة جامعة تشمل كل ما تعارف عليه الناس من الخير والبر والإحسان. والعشرة بالمعروف هي <strong>القاعدة الذهبية</strong> للحياة الزوجية.</p>

<h3>ما هي العشرة بالمعروف؟</h3>
<p>هي أن يعامل كل طرف الآخر بما يحب أن يُعامل به — من الكلمة الطيبة، والابتسامة، والصبر، والعفو، والمساعدة، وإظهار الحب، وترك الأذى.</p>

<h3>صور من عشرة النبي ﷺ لأهله</h3>

<h4>1. المداعبة واللطف</h4>
<p>قال ﷺ: <em>"إني لأتلطف بأهلي ابتغاء أن يؤجرني الله فيها"</em>. كان ﷺ يمازح أزواجه، ويسابق عائشة، ويشرب من موضع شفتها.</p>

<h4>2. إعانة الأهل</h4>
<p>سُئلت عائشة: ما كان النبي ﷺ يصنع في بيته؟ قالت: <em>"كان يكون في مهنة أهله، فإذا حضرت الصلاة خرج إلى الصلاة"</em>. كان يخصف نعله، ويرقع ثوبه، ويحلب شاته.</p>

<h4>3. الإنصات لهن</h4>
<p>كان ﷺ يستمع لحديث أزواجه، ويصبر على غيرتهن، ويواسيهن. حديث أم زرع مثال رائع على إنصاته لعائشة.</p>

<h4>4. الإحسان وإدخال السرور</h4>
<p>قال ﷺ: <em>"خيركم خيركم لأهله، وأنا خيركم لأهلي"</em>.</p>

<h3>تطبيقات عملية للعشرة بالمعروف</h3>

<h4>للزوج:</h4>
<ul>
<li>ابدأ يومك بابتسامة لزوجتك وكلمة طيبة.</li>
<li>أظهر تقديرك لما تفعله — حتى البسيط منه.</li>
<li>ساعدها في أعمال البيت، ولو من باب الأجر.</li>
<li>أحسن إلى أهلها كما تحب أن تُحسن إلى أهلك.</li>
<li>لا تتأفف من تعبها أو مرضها.</li>
<li>اصبر على ما تجد فيها من نقص — فليس أحد كاملاً.</li>
<li>أدخل السرور عليها بهدية بسيطة، كلمة، نزهة.</li>
</ul>

<h4>للزوجة:</h4>
<ul>
<li>استقبلي زوجك بوجه باش وكلمة طيبة.</li>
<li>اهتمي بمظهرك له — فحلاوة العين من أسباب الألفة.</li>
<li>قدّري تعبه في السعي على الرزق.</li>
